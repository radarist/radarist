/**
 * useBriefing
 *
 * TanStack Query hook for fetching the briefing page data. Stays in
 * `isPending` while Firebase is restoring the persisted session — the
 * consumer should render the skeleton during that window.
 *
 * On failure the query surfaces `isError` with a {@link BriefingRequestError}
 * (`error.kind`) so the consumer can render an "unavailable" / "rate-limited"
 * state with a retry, instead of the empty-inbox state.
 *
 * @example
 * ```tsx
 * const { data, isPending, isError, error, refetch } = useBriefing();
 * if (isPending) return <CardGridSkeleton cards={4} columns={1} />;
 * if (isError) return <InsightsUnavailable error={error} onRetry={refetch} />;
 * return <BriefingFeed insights={data.insights} />;
 * ```
 */
export function useBriefing() {
  const { user, loading } = useAuth();
  const queryClient = useQueryClient();
  const { events } = useAgentEventStream(!loading && !!user);
  const lastRefreshEventRef = useRef<string | null>(null);
  const query = useQuery({
    queryKey: briefingKeys.insights(user?.uid ?? 'anonymous'),
    queryFn: fetchBriefingInsights,
    enabled: !loading && !!user,
    // UX-046 visible-tab freshness: a bounded interval plus focus refetch
    // replace the old "stale until manual reload" behaviour. The interval
    // pauses automatically while the tab is hidden
    // (refetchIntervalInBackground defaults to false), and a background
    // refetch failure keeps the last-good data on screen (the feed renders
    // a stale-data note instead of swapping to the outage panel).
    staleTime: 30 * 1000,
    refetchInterval: 60 * 1000,
    refetchOnWindowFocus: true,
    // The bounded server read already retries transient errors within its
    // budget (PERF-008), so an error here is a sustained failure. Don't
    // auto-retry — surface it immediately with a manual Retry (UX-018).
    retry: false,
  });

  // A sweep completes outside the page's request lifecycle. Polling remains
  // the outage fallback, but the durable SSE event is the normal fast path:
  // invalidate both the feed and its empty-state status so the first card (or
  // a truthful quiet/failure result) appears without a page reload.
  const refreshEvent = events.findLast((event) => isBriefingRefreshEvent(event, user?.uid));
  useEffect(() => {
    if (!user || !refreshEvent || lastRefreshEventRef.current === refreshEvent.id) return;
    lastRefreshEventRef.current = refreshEvent.id;
    void Promise.all([
      queryClient.invalidateQueries({ queryKey: briefingKeys.insights(user.uid), exact: true }),
      queryClient.invalidateQueries({ queryKey: briefingKeys.status(user.uid), exact: true }),
    ]);
  }, [queryClient, refreshEvent, user]);

  return query;
}

/** Events that can change either the visible feed or its pipeline-state copy. */
export function isBriefingRefreshEvent(event: AgentEvent, userId?: string): boolean {
  if (!userId) return false;
  if (event.type === 'insight.created') return event.userId === userId;
  return event.type === 'agent.completed' && event.agentType === 'sweep-cycle';
}
