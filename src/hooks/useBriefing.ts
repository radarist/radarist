/**
 * @file hooks/useBriefing.ts
 * @description TanStack Query hook for briefing-page proactive insights.
 *
 * Fetches `ProactiveInsight` data from `/api/impulse/briefing` for the
 * `BriefingFeed` component. The query is **gated on the Firebase auth
 * state** via `useAuth()` — TanStack Query would otherwise fire on mount
 * before `onAuthStateChanged` has restored the persisted session, hit the
 * "no user" branch, and cache an empty result that nothing re-invalidates.
 * Until the gate opens, the consumer keeps showing the skeleton (`isPending`
 * stays true).
 *
 * Phase 0 step 0.10 of the 2026-05-13 briefing-pipeline cleanup.
 */

import { useEffect, useRef } from 'react';
import { useQuery, useQueryClient } from '@tanstack/react-query';
import { useAuth } from '@/components/providers/AuthProvider';
import { fetchWithAuth } from '@/lib/fetch-with-auth';
import { useAgentEventStream } from '@/hooks/useAgentEventStream';
import type { AgentEvent } from '@/lib/schemas/agent-event';

