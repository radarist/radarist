export interface ExecuteCypherResult {
  success: boolean;
  results?: unknown[];
  resultCount?: number;
  executionTimeMs?: number;
  truncated?: boolean;
  truncationReasons?: string[];
  limits?: typeof RAW_CYPHER_LIMITS;
  payloadBytes?: number;
  error?: string;
}

interface BoundedCypherExecution {
  records: Record<string, unknown>[];
  executionTimeMs: number;
  truncated: boolean;
  truncationReasons: string[];
  payloadBytes: number;
}

async function executeBoundedCypherRead(
  cypher: string,
  params: Record<string, unknown>,
  surface: 'raw' | 'generated'
): Promise<BoundedCypherExecution> {
  const startTime = Date.now();
  const queryResult = await runRawReadQuery(cypher, params, {
    transactionTimeoutMs: RAW_CYPHER_LIMITS.transactionTimeoutMs,
    wallTimeoutMs: RAW_CYPHER_LIMITS.wallTimeoutMs,
    maxRecords: RAW_CYPHER_LIMITS.records,
    maxPayloadBytes: RAW_CYPHER_LIMITS.responseBytes,
    recordMode: 'native',
    metadata: { application: 'radarist', surface: `ai-cypher-${surface}` },
  });

  return {
    records: queryResult.nativeRecords ?? [],
    executionTimeMs: Date.now() - startTime,
    truncated: queryResult.truncated,
    truncationReasons: queryResult.truncationReasons,
    payloadBytes: queryResult.payloadBytes ?? 2,
  };
}

