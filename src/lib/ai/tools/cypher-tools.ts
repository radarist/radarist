/**
 * Execute a raw Cypher query (READ-only)
 */
export async function executeExecuteCypher(args: Record<string, unknown>): Promise<ExecuteCypherResult> {
  try {
    const cypher = args.cypher;
    const params = args.params ?? {};

    if (typeof cypher !== 'string' || cypher.trim().length === 0) {
      return { success: false, error: 'cypher is required' };
    }
    if (params === null || typeof params !== 'object' || Array.isArray(params)) {
      return { success: false, error: 'params must be an object' };
    }

    const policy = inspectCypherReadQuery(cypher, params);
    if (!policy.allowed) {
      return {
        success: false,
        error: policy.reason ?? 'Only bounded read queries are allowed.',
      };
    }

    const queryResult = await executeBoundedCypherRead(cypher, params as Record<string, unknown>, 'raw');

    return {
      success: true,
      results: queryResult.records,
      resultCount: queryResult.records.length,
      executionTimeMs: queryResult.executionTimeMs,
      truncated: queryResult.truncated,
      truncationReasons: queryResult.truncationReasons,
      limits: RAW_CYPHER_LIMITS,
      payloadBytes: queryResult.payloadBytes,
    };
  } catch (error) {
    const sanitized = sanitizedToolError(error, 'Failed to execute Cypher query');
    log.error('executeCypher error', sanitized.logError);
    return {
      success: false,
      error: sanitized.message,
    };
  }
}
