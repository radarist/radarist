function sanitizedToolError(error: unknown, fallback: string): { message: string; logError?: Error } {
  if (!(error instanceof Error)) return { message: fallback };
  const message = sanitizeNeo4jErrorMessage(error.message);
  return { message, logError: new Error(message) };
}

