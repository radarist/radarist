/**
 * Generate a Cypher query from natural language and optionally execute it
 */
export async function executeGenerateCypher(args: Record<string, unknown>): Promise<GenerateCypherResult> {
  try {
    const question = args.question;
    const execute = args.execute === true;
    const requestedLimit = typeof args.limit === 'number' && Number.isFinite(args.limit) ? Math.floor(args.limit) : 20;
    const limit = Math.max(1, Math.min(requestedLimit, RAW_CYPHER_LIMITS.records));

    if (typeof question !== 'string' || question.trim().length === 0) {
      return { success: false, error: 'question is required' };
    }

    // Parse the natural language query
    const parsed = await parseNaturalLanguageQuery(question);

    // Apply limit override
    if (parsed.filters) {
      parsed.filters.limit = limit;
    } else {
      parsed.filters = { limit };
    }

    // Generate the Cypher query
    const generated: GeneratedQuery = generateCypherQuery(parsed);

    const result: GenerateCypherResult = {
      success: true,
      cypher: generated.cypher.trim(),
      explanation: generated.explanation,
      params: generated.params,
      parsedQuery: parsed,
      executed: false,
    };

    // Optionally execute the query
    if (execute) {
      if (!isSafeQuery(generated.cypher)) {
        return {
          success: false,
          error: 'Generated query contains potentially destructive operations and cannot be executed',
          cypher: generated.cypher.trim(),
          explanation: generated.explanation,
        };
      }

      try {
        const queryResult = await executeBoundedCypherRead(generated.cypher, generated.params, 'generated');

        result.results = queryResult.records;
        result.resultCount = queryResult.records.length;
        result.executionTimeMs = queryResult.executionTimeMs;
        result.truncated = queryResult.truncated;
        result.truncationReasons = queryResult.truncationReasons;
        result.limits = RAW_CYPHER_LIMITS;
        result.payloadBytes = queryResult.payloadBytes;
        result.executed = true;
      } catch (execError) {
        const message = execError instanceof Error ? sanitizeNeo4jErrorMessage(execError.message) : 'Unknown error';
        result.error = `Query generated but execution failed: ${message}`;
        result.executed = false;
      }
    }

    return result;
  } catch (error) {
    const sanitized = sanitizedToolError(error, 'Failed to generate Cypher query');
    log.error('generateCypher error', sanitized.logError);
    return {
      success: false,
      error: sanitized.message,
    };
  }
}

/**
 * Explain what a Cypher query does
 */
export async function executeExplainCypher(args: Record<string, unknown>): Promise<ExplainCypherResult> {
  try {
    const cypher = args.cypher as string;

    if (!cypher) {
      return { success: false, error: 'cypher is required' };
    }

    // Parse the query to extract components
    const components = {
      matchClauses: [] as string[],
      whereClauses: [] as string[],
      returnClauses: [] as string[],
      operations: [] as string[],
    };

    // Extract MATCH clauses
    const matchMatches = cypher.match(/MATCH\s+([^WHERE|RETURN|WITH|ORDER|LIMIT]+)/gi);
    if (matchMatches) {
      components.matchClauses = matchMatches.map((m) => m.replace(/MATCH\s+/i, '').trim());
    }

    // Extract WHERE clauses
    const whereMatches = cypher.match(/WHERE\s+([^RETURN|WITH|ORDER|LIMIT]+)/gi);
    if (whereMatches) {
      components.whereClauses = whereMatches.map((m) => m.replace(/WHERE\s+/i, '').trim());
    }

    // Extract RETURN clauses
    const returnMatches = cypher.match(/RETURN\s+([^ORDER|LIMIT]+)/gi);
    if (returnMatches) {
      components.returnClauses = returnMatches.map((m) => m.replace(/RETURN\s+/i, '').trim());
    }

    // Identify operations
    if (/\bshortestPath\b/i.test(cypher)) {
      components.operations.push('Finds shortest path between nodes');
    }
    if (/\ballShortestPaths\b/i.test(cypher)) {
      components.operations.push('Finds all shortest paths between nodes');
    }
    if (/\bCOUNT\b/i.test(cypher)) {
      components.operations.push('Counts results');
    }
    if (/\bCOLLECT\b/i.test(cypher)) {
      components.operations.push('Aggregates results into lists');
    }
    if (/\bDISTINCT\b/i.test(cypher)) {
      components.operations.push('Returns unique results only');
    }
    if (/\bORDER BY\b/i.test(cypher)) {
      components.operations.push('Sorts results');
    }
    if (/\bLIMIT\b/i.test(cypher)) {
      components.operations.push('Limits number of results');
    }

    // Build explanation
    let explanation = 'This Cypher query ';

    if (components.matchClauses.length > 0) {
      explanation += `searches for patterns: ${components.matchClauses.join(', ')}. `;
    }

    if (components.whereClauses.length > 0) {
      explanation += `It filters results where: ${components.whereClauses.join(' AND ')}. `;
    }

    if (components.returnClauses.length > 0) {
      explanation += `It returns: ${components.returnClauses.join(', ')}. `;
    }

    if (components.operations.length > 0) {
      explanation += `Additional operations: ${components.operations.join(', ')}.`;
    }

    // Check safety
    if (!isSafeQuery(cypher)) {
      explanation +=
        ' WARNING: This query contains potentially destructive operations (CREATE, DELETE, SET, etc.) and should be used with caution.';
    }

    return {
      success: true,
      explanation: explanation.trim(),
      components,
    };
  } catch (error) {
    const sanitized = sanitizedToolError(error, 'Failed to explain Cypher query');
    log.error('explainCypher error', sanitized.logError);
    return {
      success: false,
      error: sanitized.message,
    };
  }
}

/**
 * Validate if a Cypher query is safe to execute
 */
export async function executeValidateCypher(args: Record<string, unknown>): Promise<ValidateCypherResult> {
  try {
    const cypher = args.cypher as string;

    if (!cypher) {
      return { success: false, error: 'cypher is required' };
    }

    const issues: string[] = [];
    const policy = inspectCypherReadQuery(cypher);
    if (!policy.allowed && policy.reason) issues.push(policy.reason);

    // Check for potential performance issues
    if (/\[\*\]/.test(cypher) && !/\[\*\d+\.\.\d+\]/.test(cypher)) {
      issues.push('Contains unbounded variable-length path - may cause performance issues');
    }

    if (!/\bLIMIT\b/i.test(cypher) && /\bMATCH\b/i.test(cypher)) {
      issues.push('No LIMIT clause - may return large result sets');
    }

    const isSafe = policy.allowed;
    const isValid = !['EMPTY_QUERY', 'UNTERMINATED_LITERAL', 'MULTIPLE_STATEMENTS'].includes(policy.code ?? '');

    return {
      success: true,
      isValid,
      isSafe,
      issues: issues.length > 0 ? issues : undefined,
    };
  } catch (error) {
    const sanitized = sanitizedToolError(error, 'Failed to validate Cypher query');
    log.error('validateCypher error', sanitized.logError);
    return {
      success: false,
      error: sanitized.message,
    };
  }
}

