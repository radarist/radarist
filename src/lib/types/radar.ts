// Added for the "Variable Quadrants" refactor. These are the single source of
// truth for looking up, validating, and reconciling per-radar quadrant configs.
// Existing helpers above (isQuadrantConfig, normalizeQuadrants, getQuadrantName)
// stay for backward compatibility during the transition window.

/**
 * Look up a single `QuadrantConfig` by stable id on a radar.
 *
 * Returns `undefined` if the id is not present or the radar's `quadrants` field
 * is still in the legacy `string[]` shape (in which case callers should route
 * through `resolveQuadrantConfigs` first).
 */
export function getQuadrantById(radar: Pick<RadarData, 'quadrants'>, quadrantId: string): QuadrantConfig | undefined {
  if (!Array.isArray(radar.quadrants)) return undefined;
  for (const q of radar.quadrants) {
    if (isQuadrantConfig(q) && q.id === quadrantId) {
      return q;
    }
  }
  return undefined;
}

/**
 * Case-insensitive lookup of a `QuadrantConfig` by display name on a radar.
 *
 * Compatibility helper for callers that intentionally accept surrounding
 * whitespace in legacy display names. External id-or-name references use
 * `resolveQuadrantReference`; update-quadrants merging remains ID-first via
 * `reconcileQuadrantConfigs`.
 */
export function findQuadrantByName(radar: Pick<RadarData, 'quadrants'>, name: string): QuadrantConfig | undefined {
  if (!Array.isArray(radar.quadrants) || !name) return undefined;
  const target = name.trim().toLowerCase();
  if (!target) return undefined;
  for (const q of radar.quadrants) {
    if (isQuadrantConfig(q) && q.name.trim().toLowerCase() === target) {
      return q;
    }
  }
  return undefined;
}

export type QuadrantReferenceMatch = 'id-or-name' | 'id' | 'name';
export type QuadrantReferencePrecedence = 'id-first' | 'name-first';

export interface ResolveQuadrantReferenceOptions {
  /** Restrict lookup to one side when a caller receives id and name in separate fields. */
  matchBy?: QuadrantReferenceMatch;
  /** Resolve the otherwise-valid cross-collision where one config's name equals another config's id. */
  precedence?: QuadrantReferencePrecedence;
}

/**
 * Resolve an external quadrant reference to its canonical config.
 *
 * Stable ids match exactly. Display names match case-insensitively but remain
 * whitespace-sensitive, preserving the existing AI tool contract. Callers
 * that intentionally accept trimmed legacy names should keep using
 * `findQuadrantByName`.
 */
export function resolveQuadrantReference(
  radar: Pick<RadarData, 'quadrants'>,
  reference: string,
  options: ResolveQuadrantReferenceOptions = {}
): Pick<QuadrantConfig, 'id' | 'name'> | undefined {
  if (!Array.isArray(radar.quadrants) || typeof reference !== 'string') return undefined;

  const matchBy = options.matchBy ?? 'id-or-name';
  const referenceName = reference.toLowerCase();
  let byId: Pick<QuadrantConfig, 'id' | 'name'> | undefined;
  let byName: Pick<QuadrantConfig, 'id' | 'name'> | undefined;

  for (const rawQuadrant of radar.quadrants as unknown[]) {
    if (!rawQuadrant || typeof rawQuadrant !== 'object') continue;

    const quadrant = rawQuadrant as Partial<QuadrantConfig>;
    if (typeof quadrant.id !== 'string' || quadrant.id.trim().length === 0) continue;
    if (typeof quadrant.name !== 'string' || quadrant.name.trim().length === 0) continue;

    if (!byId && matchBy !== 'name' && quadrant.id === reference) {
      byId = quadrant as Pick<QuadrantConfig, 'id' | 'name'>;
    }
    if (!byName && matchBy !== 'id' && quadrant.name.toLowerCase() === referenceName) {
      byName = quadrant as Pick<QuadrantConfig, 'id' | 'name'>;
    }
  }

  if (matchBy === 'id') return byId;
  if (matchBy === 'name') return byName;
  return options.precedence === 'name-first' ? (byName ?? byId) : (byId ?? byName);
}

/**
 * Convert a legacy `quadrants` value — which may be `string[]`, mixed, or
 * already `QuadrantConfig[]` — into a canonical `QuadrantConfig[]`.
 *
 * Used by the migration script and seed data only. Runtime code should already
 * see canonical `QuadrantConfig[]` post-migration.
 *
 * The `idGenerator` is pluggable so the migration script can use
 * `defaultQuadrantIdFromName` (deterministic, slug-based) while tests can use a
 * counter-based generator for stable snapshots.
 */
export function ensureQuadrantConfigs(
  legacy: readonly (string | QuadrantConfig)[] | undefined | null,
  idGenerator: (name: string, index: number) => string
): QuadrantConfig[] {
  if (!Array.isArray(legacy) || legacy.length === 0) return [];
  return legacy.map((item, i) => {
    if (isQuadrantConfig(item)) {
      const description = item.description;
      return {
        id: item.id,
        name: item.name,
        ...(description !== undefined ? { description } : {}),
        order: typeof item.order === 'number' ? item.order : i,
      };
    }
    // Fall-through: treat as a string name
    const name = typeof item === 'string' ? item : String(item);
    return {
      id: idGenerator(name, i),
      name,
      order: i,
    };
  });
}

/**
 * Shape of a proposed quadrant from an ID-first update payload.
 *
 * - `id` present → update/preserve an existing quadrant on the radar.
 * - `id` absent  → mint a new quadrant with a generated id.
 *
 * This is the shape accepted by AI tool executors (`updateRadarSettings`) and
 * by `reconcileQuadrantConfigs` directly.
 */
export interface ProposedQuadrantConfig {
  id?: string;
  name: string;
  description?: string;
}

/**
 * Result of reconciling a proposed quadrant list against the radar's existing
 * configs. Every field is actionable by the caller:
 *
 * - `next`     — the new canonical list, in proposed order, with preserved or minted ids.
 * - `added`    — brand-new configs (no `id` on the proposed side).
 * - `removed`  — ids that existed but are absent from `proposed` (feed into orphan check).
 * - `renamed`  — preserved-id rows whose display name changed (useful for agent reports).
 * - `errors`   — validation failures; when non-empty, `next` is `[]` and callers must reject.
 */
export interface ReconcileQuadrantsResult {
  next: QuadrantConfig[];
  added: QuadrantConfig[];
  removed: string[];
  renamed: Array<{ id: string; oldName: string; newName: string }>;
  errors: string[];
}

/**
 * ID-first reconciliation of a proposed quadrant list against a radar's current
 * configs. This is the single shape-preserving merge used by every "update
 * quadrants" code path — AI tool executor, `SettingsDialog` save, and the
 * signal-approval radar-edit path.
 *
 * Behavior (strict, never guesses):
 *
 * 1. Each proposed item with `id` must match an existing quadrant. Match → preserve id,
 *    update name/description. Miss → error "Unknown quadrant id: <id>".
 * 2. Each proposed item without `id` is new → mint a fresh id via `idGenerator`.
 * 3. Existing quadrants absent from `proposed` (compared by id) are removed and
 *    their ids listed in `removed` — the caller decides whether to run an orphan
 *    check before committing.
 * 4. Validation errors: empty proposed list, empty name, duplicate ids. Range is
 *    NOT checked here (MIN/MAX_QUADRANTS enforced by the service layer).
 *
 * When `errors` is non-empty the other fields are empty — callers should reject
 * the input and return the error list to the user/agent.
 */
export function reconcileQuadrantConfigs(
  existing: readonly QuadrantConfig[],
  proposed: readonly ProposedQuadrantConfig[],
  idGenerator: (name: string, index: number) => string
): ReconcileQuadrantsResult {
  const errors: string[] = [];

  if (proposed.length === 0) {
    errors.push('At least 1 quadrant is required');
    return { next: [], added: [], removed: [], renamed: [], errors };
  }

  // Build existing id → config lookup
  const existingById = new Map<string, QuadrantConfig>();
  for (const q of existing) {
    existingById.set(q.id, q);
  }

  // First pass: validate shapes and duplicate-id detection
  const seenIds = new Set<string>();
  const seenNames = new Set<string>();
  for (let i = 0; i < proposed.length; i++) {
    const item = proposed[i];
    const trimmedName = (item.name ?? '').trim();
    if (!trimmedName) {
      errors.push(`Quadrant at index ${i} has an empty name`);
      continue;
    }
    const lowerName = trimmedName.toLowerCase();
    if (seenNames.has(lowerName)) {
      errors.push(`Duplicate quadrant name: "${trimmedName}"`);
      continue;
    }
    seenNames.add(lowerName);
    if (item.id) {
      if (seenIds.has(item.id)) {
        errors.push(`Duplicate quadrant id: ${item.id}`);
        continue;
      }
      seenIds.add(item.id);
      if (!existingById.has(item.id)) {
        errors.push(
          `Unknown quadrant id: ${item.id}. Retry with an id from the current radar, or omit id to create a new quadrant.`
        );
      }
    }
  }

  if (errors.length > 0) {
    return { next: [], added: [], removed: [], renamed: [], errors };
  }

  // Second pass: build the next list
  const next: QuadrantConfig[] = [];
  const added: QuadrantConfig[] = [];
  const renamed: Array<{ id: string; oldName: string; newName: string }> = [];
  const keptIds = new Set<string>();

  for (let i = 0; i < proposed.length; i++) {
    const item = proposed[i];
    const trimmedName = item.name.trim();

    if (item.id) {
      // Validated above — safe to assert existingItem is present
      const existingItem = existingById.get(item.id)!;
      const description = item.description ?? existingItem.description;
      const updated: QuadrantConfig = {
        id: existingItem.id,
        name: trimmedName,
        ...(description !== undefined ? { description } : {}),
        order: i,
      };
      next.push(updated);
      keptIds.add(item.id);
      if (existingItem.name !== trimmedName) {
        renamed.push({ id: item.id, oldName: existingItem.name, newName: trimmedName });
      }
    } else {
      const minted: QuadrantConfig = {
        id: idGenerator(trimmedName, i),
        name: trimmedName,
        ...(item.description !== undefined ? { description: item.description } : {}),
        order: i,
      };
      next.push(minted);
      added.push(minted);
    }
  }

  // Third pass: compute removed ids
  const removed: string[] = [];
  for (const q of existing) {
    if (!keptIds.has(q.id)) {
      removed.push(q.id);
    }
  }

  return { next, added, removed, renamed, errors: [] };
}
