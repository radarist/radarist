/**
 * Represents the entire state of a Radar instance.
 * Supports dynamic quadrant and ring configurations.
 * @phase Phase 2 Task 2.1.3 - Updated for dynamic quadrants/rings
 */
export interface RadarData {
  /** Unique string ID for the radar. */
  id: string;
  /** Display name of the radar. */
  name: string;
  /** URL-friendly slug for the radar. */
  slug?: string;
  /** Optional description of the radar's purpose. */
  description?: string;

  /**
   * Canonical list of quadrants on this radar.
   *
   * Always `QuadrantConfig[]` post-migration. Length is bounded to
   * `MIN_QUADRANTS..MAX_QUADRANTS` (1..8) by the service layer. Each entry
   * has a stable `id` that placements/entries reference via `quadrantId`.
   *
   * Pre-migration radar docs may still carry `string[]` here — use
   * `resolveQuadrantConfigs(radar)` on every read surface during the
   * transition window.
   */
  quadrants: QuadrantConfig[];

  /**
   * Optional ring configuration.
   * When not provided, defaults to the ring system's standard rings.
   */
  ringConfigs?: RingConfig[];

  /** List of entries on the radar. */
  entries: RadarEntry[];

  /** The ring system configuration used (e.g., "Standard" or "TRL"). */
  ringSystem?: RingSystem; // Optional for backward compatibility, defaults to Standard

  /**
   * Public-link opt-in (AUDIT-001). `/share/{radarId}` renders ONLY when this
   * is exactly `true` — absent/false fails closed, matching the report and
   * visualization share gates. Toggled from ShareDialog; never set at create.
   */
  shared?: boolean;

  /** When the radar was created (Unix timestamp). */
  createdAt?: number;
  /** When the radar was last updated (Unix timestamp). */
  updatedAt?: number;
  /** User ID of who created this radar. */
  createdBy?: string;
}

