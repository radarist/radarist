/**
 * Type guard to check if quadrant is a QuadrantConfig object.
 * @phase Phase 2 Task 2.1.3
 */
export function isQuadrantConfig(quadrant: Quadrant | QuadrantConfig): quadrant is QuadrantConfig {
  return typeof quadrant === 'object' && quadrant !== null && 'id' in quadrant;
}

/**
 * Normalize quadrants to string array for backward compatibility.
 * Handles both legacy string arrays and new QuadrantConfig arrays.
 * @phase Phase 2 Task 2.1.3
 *
 * @example
 * ```typescript
 * // Legacy format
 * normalizeQuadrants(['Techniques', 'Tools', 'Platforms', 'Languages'])
 * // Returns: ['Techniques', 'Tools', 'Platforms', 'Languages']
 *
 * // New format
 * normalizeQuadrants([{ id: 'q1', name: 'AI & ML', order: 0 }, ...])
 * // Returns: ['AI & ML', ...]
 * ```
 */
export function normalizeQuadrants(quadrants: Quadrant[] | QuadrantConfig[]): string[] {
  if (!Array.isArray(quadrants)) return [];
  if (quadrants.length === 0) return [];

  // Check if first item is a QuadrantConfig
  if (isQuadrantConfig(quadrants[0])) {
    return (quadrants as QuadrantConfig[]).map((q) => q.name);
  }

  // Already a string array
  return quadrants as string[];
}

/**
 * Get quadrant name from a quadrant value (handles both string and QuadrantConfig).
 * @phase Phase 2 Task 2.1.3
 */
export function getQuadrantName(quadrant: Quadrant | QuadrantConfig): string {
  if (isQuadrantConfig(quadrant)) {
    return quadrant.name;
  }
  return quadrant;
}

